export async function seedRoomCosmetics() {
  await prisma.$transaction(
    DEFAULT_ROOM_COSMETICS.map(({ id, ...asset }) =>
      prisma.cosmeticAsset.upsert({
        where: { id },
        create: { id, ...asset },
        update: asset,
      }),
    ),
  );
}

async function main() {
  console.log("Seeding Room Cosmetics catalog...");
  await seedRoomCosmetics();
  console.log(`Seeded ${DEFAULT_ROOM_COSMETICS.length} Room Cosmetics assets.`);
}

const isDirectExecution =
  process.argv[1] !== undefined &&
  import.meta.url === pathToFileURL(process.argv[1]).href;

if (isDirectExecution) {
  main()
    .catch((error) => {
      console.error("Room Cosmetics seed failed:", error);
      process.exit(1);
    })
    .finally(async () => {
      await prisma.$disconnect();
    });
}
